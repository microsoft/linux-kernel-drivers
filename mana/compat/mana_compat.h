/*
 * MANA out-of-tree compat umbrella.
 *
 * This header is FORCE-INCLUDED at the top of every translation unit via
 * `ccflags-y += -include $(src)/compat/mana_compat.h` (see ../Kbuild). The
 * driver sources under ../driver/ are a verbatim snapshot of the in-tree 7.1
 * MANA driver and are never edited for compat reasons; all kernel-version
 * adaptation lives here and in the sibling compat/ headers + backport-include/
 * overlays.
 *
 * Include order is deliberate:
 *   1. Require the complete MANA_HAVE_* feature map generated by ./configure
 *      for this exact target kernel. Missing or incomplete maps are fatal.
 *   2. Pull in <linux/export.h> and override EXPORT_SYMBOL_NS so the verbatim
 *      string-literal namespace compiles on pre-6.13 kernels.
 *   3. Layer the feature shims. Each only fills a gap (guarded by MANA_HAVE_*
 *      or #ifndef); none overrides a symbol the target kernel already provides.
 *
 * The backport-include/ overlays (net/net_shaper.h, net/netdev_lock.h,
 * net/page_pool/helpers.h) are resolved separately via NOSTDINC_FLAGS so the
 * driver's verbatim `#include <net/...>` lines keep working on old kernels.
 */
#ifndef MANA_COMPAT_H
#define MANA_COMPAT_H

/* ---- 1. Feature map ---------------------------------------------------- */

#include "autogen/mana_compat_autoconf.h"
#include "mana_compat_features.h"

/* ---- 2. Symbol export -------------------------------------------------- */

#include "mana_compat_export.h"

/* ---- 3. Feature shims -------------------------------------------------- */

#include "mana_compat_alloc.h"
#include "mana_compat_kernel.h"
#include "mana_compat_cleanup.h"
#include "mana_compat_cpumask.h"
#include "mana_compat_pci.h"
#include "mana_compat_netdev.h"
#include "mana_compat_ethtool.h"
#include "mana_compat_dim.h"
#include "mana_compat_xdp.h"

/* ---- 4. Out-of-tree control surfaces ---------------------------------- */
/*
 * Not a kernel-gap shim: an additive, always-present control plane the
 * out-of-tree module owns (ethtool private flags). Declarations only -- the
 * definitions are out-of-line in mana_compat_privflags.c -- so force-including
 * this ahead of the vendored headers under <net/mana/> stays safe.
 */
#include "mana_compat_privflags.h"
#include "mana_compat_ethtool_ops.h"

#endif /* MANA_COMPAT_H */
